document.addEventListener('DOMContentLoaded', function () {
  const tagsBtn = document.getElementById('tags-button');
  const tagsPanel = document.getElementById('tags-panel');

  function closePanel() {
    tagsPanel.classList.remove('show');
    tagsPanel.setAttribute('aria-hidden', 'true');
  }

  if (tagsBtn && tagsPanel) {
    tagsBtn.addEventListener('click', function (event) {
      event.stopPropagation();
      const isShown = tagsPanel.classList.toggle('show');
      tagsPanel.setAttribute('aria-hidden', isShown ? 'false' : 'true');
    });

    tagsPanel.addEventListener('click', function (event) {
      event.stopPropagation();
    });

    document.addEventListener('click', function () {
      if (tagsPanel.classList.contains('show')) {
        closePanel();
      }
    });

    document.addEventListener('keydown', function (e) {
      if (e.key === 'Escape' && tagsPanel.classList.contains('show')) {
        closePanel();
      }
    });
  }
});
